const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
test('draft-storage failure is disclosed without misreporting a successful file save',async()=>{
 const context={structuredClone,setTimeout,clearTimeout,localStorage:{setItem(){throw new Error('Unavailable');},removeItem(){throw new Error('Unavailable');}}};
 vm.createContext(context);
 vm.runInContext(fs.readFileSync(path.join(__dirname,'../prototype/file-session.js'),'utf8'),context);
 let message='',saved=null;
 const workspace={version:4,records:{note:{body:'Changed'}}};
 const session=new context.BentoFileSession({save:async value=>{saved=value;return {ok:true,value:{workspace:value,folder:'test',readOnly:false}};}},{workspace:()=>workspace,status:value=>{message=value;},error:value=>{assert.equal(value,'');}});
 session.view={workspace:{version:4,records:{note:{body:'Original'}}},folder:'test',readOnly:false};
 session.changed(workspace);
 assert.match(message,/draft storage unavailable/);
 await session.save();
 assert.equal(saved.records.note.body,'Changed');
 assert.equal(session.failed,false);
 assert.equal(session.dirty,false);
 assert.match(message,/Saved to workspace files/);
});
