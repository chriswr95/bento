import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import * as markdown from '../files/markdown.js';
import { WorkspaceRepository } from '../files/repository.js';

export async function checkPropertyLayout({ launch, stop, temporary, root }) {
  const folder = path.join(temporary, 'Property workspace'), userData = path.join(temporary, 'PropertyUserData');
  await fs.cp(path.join(root, 'examples/document-databases'), folder, { recursive: true });
  const definition = path.join(folder, 'meetings/database.md'), raw = await fs.readFile(definition, 'utf8');
  const parsed = markdown.parse(raw);
  parsed.metadata.fields.find(field => field.id === 'field-meeting-date').required = true;
  parsed.metadata.fields.push({ id: 'reviewer', name: 'Reviewer', type: 'text' });
  await fs.writeFile(definition, markdown.serialize({ ...parsed.metadata, body: parsed.body }, raw));
  let repo = await WorkspaceRepository.open(folder);
  const note = repo.workspace.records['meeting-coordination'], original = await fs.readFile(path.join(folder, repo.workspace.paths[note.id]), 'utf8');
  await fs.writeFile(path.join(folder, 'meetings/second.md'), markdown.serialize({ ...note, id: 'second-meeting', title: 'Second meeting' }));
  let launched = await launch(folder, userData), app = launched.app, page = launched.page;
  const errors = []; const listen = () => page.on('pageerror', error => errors.push(error.message)); listen();
  const open = title => page.locator('aside').getByRole('button', { name: title, exact: true }).click();
  const arrange = () => page.getByRole('button', { name: 'Arrange properties', exact: true }).click();
  const dialog = () => page.getByRole('dialog', { name: 'Arrange properties', exact: true });
  try {
    await open(note.title);
    const more = () => page.locator('[data-more-properties]>summary');
    assert.equal(await more().innerText(), 'More');
    await more().click(); assert.equal(await more().innerText(), 'Less');
    assert.equal(await page.getByRole('button', { name: 'Edit Tags', exact: true }).isVisible(), true);
    await more().click();
    await arrange();
    await page.keyboard.press('ControlOrMeta+p');
    assert.equal(await page.getByRole('dialog', { name: 'Quick open', exact: true }).isVisible(), false);
    assert.equal(await dialog().locator('.b-layout-required').innerText(), '*\nMeeting date');
    assert.equal(await dialog().getByRole('button', { name: 'Reorder Meeting date', exact: true }).count(), 0);
    const handle = dialog().getByRole('button', { name: 'Reorder Related projects', exact: true });
    await handle.dragTo(dialog().getByRole('list', { name: 'Detail properties', exact: true }));
    await dialog().getByRole('list', { name: 'Detail properties', exact: true }).getByRole('button', { name: 'Reorder Related projects', exact: true }).waitFor();
    await dialog().getByRole('button', { name: 'Move Color to Important', exact: true }).click();
    await dialog().getByRole('button', { name: 'Reorder Color', exact: true }).press('Alt+ArrowUp');
    assert.deepEqual(await dialog().locator('[data-layout-group="important"] [data-layout-field]').evaluateAll(rows => rows.map(row => row.dataset.layoutField)), ['$color', 'reviewer']);
    await page.screenshot({ path: path.join(root, 'work/qa/property-layout.png') });
    await dialog().getByRole('button', { name: 'Save layout', exact: true }).click();
    await dialog().waitFor({ state: 'hidden' });
    repo = await WorkspaceRepository.open(folder);
    const saved = repo.workspace.databases['db-meetings'].property_layout;
    assert.deepEqual(saved.important, ['$color', 'reviewer']);
    assert.ok(saved.detail.includes('field-meeting-projects'));
    assert.equal(await fs.readFile(path.join(folder, repo.workspace.paths[note.id]), 'utf8'), original);
    assert.equal(await page.getByRole('button', { name: 'Edit Reviewer', exact: true }).isVisible(), true);
    assert.equal(await page.getByRole('button', { name: 'Edit Related projects', exact: true }).isVisible(), false);
    await more().focus(); await more().press('Enter');
    assert.equal(await more().innerText(), 'Less');
    await page.getByRole('button', { name: 'Edit Related projects', exact: true }).waitFor();
    await open('Second meeting');
    assert.equal(await page.getByRole('button', { name: 'Edit Related projects', exact: true }).isVisible(), false);
    await page.getByRole('button', { name: 'Edit Reviewer', exact: true }).waitFor();
    await arrange();
    await dialog().getByRole('button', { name: 'Reorder Reviewer', exact: true }).press('Alt+ArrowRight');
    await dialog().getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.deepEqual((await WorkspaceRepository.open(folder)).workspace.databases['db-meetings'].property_layout, saved);
    await stop(app); app = null;
    launched = await launch(null, userData); app = launched.app; page = launched.page; listen();
    await page.getByRole('button', { name: 'Edit Reviewer', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Edit Related projects', exact: true }).isVisible(), false);
    assert.equal(await page.getByRole('button', { name: 'Edit Meeting date', exact: true }).isVisible(), true);
    assert.deepEqual(errors, []);
    console.log('Passed animated More/Less, required pinning, real drag/drop, keyboard ordering and grouping, cancellation, shared layouts, unchanged document bytes, and restart.');
  } finally { await stop(app); }
}
