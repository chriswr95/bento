import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { WorkspaceRepository } from '../files/repository.js';
import model from '../prototype/workspace.js';
export async function checkOnboarding({ launch, stop, temporary, root }) {
  const folder = path.join(temporary, 'Example'), userData = path.join(temporary, 'ExampleUser');
  await fs.mkdir(folder);
  let { app, page } = await launch(null, userData);
  for (const width of [380, 736, 1160]) {
    await page.setViewportSize({ width, height: 900 });
    await page.getByRole('heading', { name: 'Your projects, notes, and next steps.' }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Welcome overflow ' + width);
    await page.locator('.b-welcome-art').evaluate(element => element.getAnimations().forEach(animation => animation.finish()));
    await page.screenshot({ path: path.join(root, `work/qa/welcome-${width}.png`) });
  }
  const openExample = () => page.getByRole('button', { name: 'Try an example workspace', exact: true }).click();
  await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
  await openExample();
  await page.getByRole('heading', { name: 'Your projects, notes, and next steps.' }).waitFor();
  assert.deepEqual(await fs.readdir(folder), []);
  await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, folder);
  await openExample();
  const guide = () => page.getByRole('region', { name: 'Getting started', exact: true });
  await guide().getByRole('button', { name: 'Start with a project', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Project Markdown', exact: true }).waitFor();
  await page.locator('#b-save-state').filter({ hasText: /^Saved$/ }).waitFor();
  await page.locator('#bento-workflow').screenshot({ path: path.join(root, 'work/qa/onboarding-project.png') });
  for (const width of [380, 736, 1160]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Walkthrough overflow ' + width);
  }
  await guide().getByRole('button', { name: 'Try meeting notes', exact: true }).click();
  await guide().getByRole('button', { name: 'Back', exact: true }).click();
  await guide().getByRole('button', { name: 'Start with a project', exact: true }).waitFor();
  await guide().getByRole('button', { name: 'Try meeting notes', exact: true }).click();
  const editor = page.getByRole('textbox', { name: 'Page Markdown', exact: true });
  await editor.click(); await editor.press('ControlOrMeta+End'); await editor.press('Enter');
  await editor.pressSequentially('[] '); await editor.pressSequentially('My walkthrough action');
  await page.locator('#b-save-state').filter({ hasText: /^Saved$/ }).waitFor();
  let repository = await WorkspaceRepository.open(folder);
  const action = model.allTasks(repository.workspace).find(task => task.title === 'My walkthrough action');
  assert.ok(action); assert.equal(action.project, repository.info.walkthrough.project);
  await app.close();
  ({ app, page } = await launch(null, userData));
  await guide().getByRole('button', { name: 'Capture a meeting and its actions', exact: true }).waitFor();
  assert.match(await editorFor(page).innerText(), /My walkthrough action/);
  await guide().getByRole('button', { name: 'Review upcoming work', exact: true }).click();
  await page.locator('main').getByRole('button', { name: 'My walkthrough action', exact: true }).waitFor();
  await page.getByRole('heading', { name: /^Today / }).waitFor();
  await page.getByRole('heading', { name: /^Upcoming / }).waitFor();
  await page.getByRole('checkbox', { name: 'Complete Review the marked-up path comments', exact: true }).click();
  await page.locator('#b-save-state').filter({ hasText: /^Saved$/ }).waitFor();
  repository = await WorkspaceRepository.open(folder);
  assert.match(repository.workspace.records[repository.info.walkthrough.meeting].body, /\[x\] \[Review the marked-up path comments\]/);
  await guide().getByRole('button', { name: 'Finish walkthrough', exact: true }).click();
  assert.equal(await guide().count(), 0);
  await page.getByRole('region', { name: 'Walkthrough complete', exact: true }).getByRole('button', { name: 'Keep exploring', exact: true }).click();
  assert.equal(await page.getByRole('region', { name: 'Walkthrough complete', exact: true }).count(), 0);
  await app.close(); ({ app, page } = await launch(null, userData));
  await page.getByRole('heading', { name: 'Active projects', exact: true }).waitFor();
  assert.equal(await guide().count(), 0);
  await page.locator('.b-workspace-menu>summary').click();
  await page.getByRole('button', { name: 'Replay walkthrough', exact: true }).click();
  await guide().getByRole('button', { name: 'Start with a project', exact: true }).waitFor();
  await guide().getByRole('button', { name: 'Skip walkthrough', exact: true }).click();
  assert.equal(await guide().count(), 0);
  const ownFolder = path.join(temporary, 'My work'); await fs.mkdir(ownFolder);
  await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, ownFolder);
  await page.locator('.b-workspace-menu>summary').click();
  await page.getByRole('button', { name: 'New workspace', exact: true }).click();
  await page.getByRole('heading', { name: 'Create your first project', exact: true }).waitFor();
  assert.equal(await guide().count(), 0);
  await page.locator('.b-workspace-menu>summary').click();
  assert.equal(await page.getByRole('button', { name: 'Replay walkthrough', exact: true }).isVisible(), false);
  assert.equal(await page.getByRole('button', { name: 'Try an example workspace', exact: true }).isVisible(), true);
  assert.equal(Object.keys((await WorkspaceRepository.open(ownFolder)).workspace.records).length, 1);
  assert.equal(Object.keys((await WorkspaceRepository.open(folder)).workspace.records).length, 10);
  await stop(app);
  console.log('Passed example creation/cancel, guided project → meeting → review, checkbox capture/completion, relative dates, restart progress, finish/replay/skip and responsive layout.');
}
const editorFor = page => page.getByRole('textbox', { name: 'Page Markdown', exact: true });
